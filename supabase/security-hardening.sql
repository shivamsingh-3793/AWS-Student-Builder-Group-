CREATE TABLE IF NOT EXISTS public.admin_sessions (
  id uuid PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz NULL
);

CREATE INDEX IF NOT EXISTS admin_sessions_user_expiry_idx
  ON public.admin_sessions (user_id, expires_at);

ALTER TABLE public.admin_sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.admin_sessions FROM anon, authenticated;
GRANT ALL ON TABLE public.admin_sessions TO service_role;

CREATE TABLE IF NOT EXISTS public.admin_audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id bigint NULL REFERENCES public.users(id) ON DELETE SET NULL,
  action text NOT NULL CHECK (length(action) <= 100),
  entity text NOT NULL CHECK (length(entity) <= 50),
  entity_id text NULL CHECK (length(entity_id) <= 100),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS admin_audit_logs_recent_idx
  ON public.admin_audit_logs (created_at DESC);

ALTER TABLE public.admin_audit_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.admin_audit_logs FROM anon, authenticated;
GRANT ALL ON TABLE public.admin_audit_logs TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.admin_audit_logs_id_seq TO service_role;
