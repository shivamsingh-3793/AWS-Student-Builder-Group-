CREATE TABLE IF NOT EXISTS public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  name text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'admin',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  slug text NOT NULL UNIQUE,
  description text NOT NULL,
  event_date date NOT NULL,
  location text NOT NULL,
  type text NOT NULL,
  image_url text NOT NULL DEFAULT '',
  featured boolean NOT NULL DEFAULT false,
  published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.posts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  slug text NOT NULL UNIQUE,
  excerpt text NOT NULL DEFAULT '',
  category text NOT NULL DEFAULT 'AWS',
  content text NOT NULL,
  image_url text NOT NULL DEFAULT '',
  published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.projects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  description text NOT NULL,
  tech_stack text NOT NULL DEFAULT '',
  image_url text NOT NULL DEFAULT '',
  project_url text NOT NULL DEFAULT '',
  architecture_url text NOT NULL DEFAULT '',
  featured boolean NOT NULL DEFAULT false,
  published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.gallery (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  category text NOT NULL DEFAULT 'Workshop',
  image_url text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.team_members (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(trim(name)) > 0),
  title text NOT NULL CHECK (length(trim(title)) > 0),
  bio text NOT NULL DEFAULT '',
  photo_url text NOT NULL DEFAULT '',
  category text NOT NULL DEFAULT 'core'
    CHECK (category IN ('leader', 'core', 'member', 'former')),
  linkedin text NOT NULL DEFAULT '',
  github text NOT NULL DEFAULT '',
  instagram text NOT NULL DEFAULT '',
  display_order integer NOT NULL DEFAULT 0 CHECK (display_order >= 0),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL DEFAULT 'join',
  name text NOT NULL,
  email text NOT NULL,
  role text NOT NULL DEFAULT '',
  track text NOT NULL DEFAULT '',
  message text NOT NULL DEFAULT '',
  event_id bigint NULL REFERENCES public.events(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.community_stats (
  id smallint PRIMARY KEY CHECK (id = 1),
  builders_count integer NOT NULL DEFAULT 540,
  events_count integer NOT NULL DEFAULT 42,
  projects_count integer NOT NULL DEFAULT 24,
  workshops_count integer NOT NULL DEFAULT 110,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.app_config (
  key text PRIMARY KEY,
  value text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.admin_sessions (
  id uuid PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz NULL
);

CREATE TABLE IF NOT EXISTS public.admin_audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id bigint NULL REFERENCES public.users(id) ON DELETE SET NULL,
  action text NOT NULL CHECK (length(action) <= 100),
  entity text NOT NULL CHECK (length(entity) <= 50),
  entity_id text NULL CHECK (length(entity_id) <= 100),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS events_public_listing_idx
  ON public.events (featured DESC, event_date ASC, id DESC)
  WHERE published = true;
CREATE INDEX IF NOT EXISTS posts_public_listing_idx
  ON public.posts (created_at DESC, id DESC)
  WHERE published = true;
CREATE INDEX IF NOT EXISTS projects_public_listing_idx
  ON public.projects (featured DESC, created_at DESC, id DESC)
  WHERE published = true;
CREATE INDEX IF NOT EXISTS gallery_listing_idx
  ON public.gallery (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS team_members_public_listing_idx
  ON public.team_members (display_order ASC, id ASC)
  WHERE active = true;
CREATE INDEX IF NOT EXISTS submissions_event_id_idx
  ON public.submissions (event_id);
CREATE INDEX IF NOT EXISTS submissions_recent_idx
  ON public.submissions (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS admin_sessions_user_expiry_idx
  ON public.admin_sessions (user_id, expires_at);
CREATE INDEX IF NOT EXISTS admin_audit_logs_recent_idx
  ON public.admin_audit_logs (created_at DESC);

